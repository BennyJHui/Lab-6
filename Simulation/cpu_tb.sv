module cpu_tb();

reg clk, reset, s, load;
reg [15:0] in;

wire [15:0] out;
wire N, V, Z, w;

cpu DUT(
    .clk(clk),
    .reset(reset),
    .s(s),
    .load(load),
    .in(in),
    .out(out),
    .N(N),
    .V(V),
    .Z(Z),
    .w(w)
);


// Clock
initial begin
    clk = 0;
    forever begin
        #5 clk = 1;
        #5 clk = 0;
    end
end


initial begin

    reset = 1;
    s = 0;
    load = 0;
    in = 16'b0;

    // Reset CPU
    #10;
    reset = 0;
    #10;


    // =====================================================
    // TEST 1: MOV R0, #7
    //
    // Expected:
    // R0 = 7
    // =====================================================

    in = {3'b110, 2'b10, 3'b000, 8'd7};
    load = 1;
    #10;

    load = 0;
    s = 1;
    #10;

    s = 0;

    // Wait for instruction to finish
    #50;


    // =====================================================
    // TEST 2: MOV R1, #2
    //
    // Expected:
    // R1 = 2
    // =====================================================

    in = {3'b110, 2'b10, 3'b001, 8'd2};
    load = 1;
    #10;

    load = 0;
    s = 1;
    #10;

    s = 0;
    #50;


    // =====================================================
    // TEST 3:
    // ADD R2, R1, R0, LSL #1
    //
    // R1 = 2
    // R0 = 7
    //
    // 2 + (7 << 1)
    // = 2 + 14
    // = 16
    //
    // Expected:
    // R2 = 16
    // =====================================================

    in = {
        3'b101,   // opcode
        2'b00,    // ADD
        3'b001,   // Rn = R1
        3'b010,   // Rd = R2
        2'b01,    // LSL #1
        3'b000    // Rm = R0
    };

    load = 1;
    #10;

    load = 0;
    s = 1;
    #10;

    s = 0;
    #60;


    // =====================================================
    // TEST 4:
    // MOV R3, R0, LSL #1
    //
    // R0 = 7
    // 7 << 1 = 14
    //
    // Expected:
    // R3 = 14
    // =====================================================

    in = {
        3'b110,
        2'b00,
        3'b000,
        3'b011,   // Rd = R3
        2'b01,    // LSL #1
        3'b000    // Rm = R0
    };

    load = 1;
    #10;

    load = 0;
    s = 1;
    #10;

    s = 0;
    #50;


    // =====================================================
    // TEST 5:
    // AND R4, R0, R3
    //
    // R0 = 7  = 0111
    // R3 = 14 = 1110
    //
    // 0111 & 1110 = 0110 = 6
    //
    // Expected:
    // R4 = 6
    // =====================================================

    in = {
        3'b101,
        2'b10,    // AND
        3'b000,   // Rn = R0
        3'b100,   // Rd = R4
        2'b00,    // no shift
        3'b011    // Rm = R3
    };

    load = 1;
    #10;

    load = 0;
    s = 1;
    #10;

    s = 0;
    #60;


    // =====================================================
    // TEST 6:
    // CMP R0, R0
    //
    // 7 - 7 = 0
    //
    // Expected:
    // Z = 1
    // N = 0
    // V = 0
    // =====================================================

    in = {
        3'b101,
        2'b01,    // CMP
        3'b000,   // Rn = R0
        3'b000,   // unused
        2'b00,    // no shift
        3'b000    // Rm = R0
    };

    load = 1;
    #10;

    load = 0;
    s = 1;
    #10;

    s = 0;
    #50;


    // =====================================================
    // TEST 7:
    // MVN R5, R1
    //
    // R1 = 0000_0000_0000_0010
    //
    // ~R1 = 1111_1111_1111_1101
    //
    // Expected:
    // R5 = 16'hFFFD
    // =====================================================

    in = {
        3'b101,
        2'b11,    // MVN
        3'b000,   // unused
        3'b101,   // Rd = R5
        2'b00,    // no shift
        3'b001    // Rm = R1
    };

    load = 1;
    #10;

    load = 0;
    s = 1;
    #10;

    s = 0;
    #50;


    $stop;

end

endmodule