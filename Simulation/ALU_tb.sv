module ALU_tb();

reg [15:0] Ain_tb, Bin_tb;
reg [1:0] ALUop_tb;

wire [15:0] out_tb;
wire Z_tb, N_tb, V_tb;


// DUT
ALU DUT(
    .Ain(Ain_tb),
    .Bin(Bin_tb),
    .ALUop(ALUop_tb),
    .out(out_tb),
    .Z(Z_tb),
    .N(N_tb),
    .V(V_tb)
);


initial begin

    // --------------------------------
    // Test ADD: 13 + 11 = 24
    // Expected:
    // out = 16'h0018
    // Z = 0, N = 0, V = 0
    // --------------------------------
    Ain_tb = 16'd13;
    Bin_tb = 16'd11;
    ALUop_tb = 2'b00;
    #10;


    // --------------------------------
    // Test SUB: 13 - 11 = 2
    // Expected:
    // out = 16'h0002
    // Z = 0, N = 0, V = 0
    // --------------------------------
    Ain_tb = 16'd13;
    Bin_tb = 16'd11;
    ALUop_tb = 2'b01;
    #10;


    // --------------------------------
    // Test AND
    // 13 = 1101
    // 11 = 1011
    //      ----
    //       1001 = 9
    // Expected out = 16'h0009
    // --------------------------------
    Ain_tb = 16'd13;
    Bin_tb = 16'd11;
    ALUop_tb = 2'b10;
    #10;


    // --------------------------------
    // Test NOT Bin
    // ~11 = ~0000_0000_0000_1011
    //     = 1111_1111_1111_0100
    //
    // Expected:
    // out = 16'hFFF4
    // Z = 0
    // N = 1
    // --------------------------------
    Ain_tb = 16'd13;
    Bin_tb = 16'd11;
    ALUop_tb = 2'b11;
    #10;


    // --------------------------------
    // Test negative SUB: 11 - 13 = -2
    //
    // Expected:
    // out = 16'hFFFE
    // Z = 0
    // N = 1
    // V = 0
    // --------------------------------
    Ain_tb = 16'd11;
    Bin_tb = 16'd13;
    ALUop_tb = 2'b01;
    #10;


    // --------------------------------
    // Test Z flag: 11 - 11 = 0
    //
    // Expected:
    // out = 16'h0000
    // Z = 1
    // N = 0
    // V = 0
    // --------------------------------
    Ain_tb = 16'd11;
    Bin_tb = 16'd11;
    ALUop_tb = 2'b01;
    #10;


    // ============================================
    // OVERFLOW TESTS
    // ============================================


    // --------------------------------
    // Positive ADD overflow
    //
    // 32767 + 1
    //
    // Expected:
    // out = 16'h8000
    // Z = 0
    // N = 1
    // V = 1
    // --------------------------------
    Ain_tb = 16'h7FFF;
    Bin_tb = 16'h0001;
    ALUop_tb = 2'b00;
    #10;


    // --------------------------------
    // Negative ADD overflow
    //
    // -32768 + (-1)
    //
    // Expected:
    // out = 16'h7FFF
    // Z = 0
    // N = 0
    // V = 1
    // --------------------------------
    Ain_tb = 16'h8000;
    Bin_tb = 16'hFFFF;
    ALUop_tb = 2'b00;
    #10;


    // --------------------------------
    // SUB overflow
    //
    // 32767 - (-1)
    //
    // Expected:
    // out = 16'h8000
    // Z = 0
    // N = 1
    // V = 1
    // --------------------------------
    Ain_tb = 16'h7FFF;
    Bin_tb = 16'hFFFF;
    ALUop_tb = 2'b01;
    #10;


    // --------------------------------
    // SUB overflow
    //
    // -32768 - 1
    //
    // Expected:
    // out = 16'h7FFF
    // Z = 0
    // N = 0
    // V = 1
    // --------------------------------
    Ain_tb = 16'h8000;
    Bin_tb = 16'h0001;
    ALUop_tb = 2'b01;
    #10;

end

endmodule